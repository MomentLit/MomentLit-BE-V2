-- ============================================================
-- SPACE ROOM (3D 방 모델)
-- 공간당 하나. 호스트가 파노라마(이후 도면)로 만든다. 좌표는 모두 미터 단위.
-- ============================================================
CREATE TABLE spaces.space_rooms (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    space_id        BIGINT NOT NULL,
    scene_id        BIGINT,
    source          VARCHAR(20) NOT NULL,
    image_url       VARCHAR(255),
    ceiling_height  DOUBLE PRECISION NOT NULL,
    camera_height   DOUBLE PRECISION,
    area_m2         DOUBLE PRECISION NOT NULL,
    geometry        JSONB NOT NULL,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_space_rooms PRIMARY KEY (id),
    CONSTRAINT uk_space_rooms_space_id UNIQUE (space_id)
);

-- ============================================================
-- SPACE ROOM LAYOUT (사용자가 저장한 가구 배치)
-- 로그인한 사용자가 3D 방에 놓아 본 가구. 이름을 붙여 공간마다 여러 개(서비스에서 20개까지) 저장한다.
-- ============================================================
CREATE TABLE spaces.space_room_layouts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    space_id    BIGINT NOT NULL,
    user_id     VARCHAR(255) NOT NULL,
    name        VARCHAR(50) NOT NULL,
    furniture   JSONB NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_space_room_layouts PRIMARY KEY (id)
);

CREATE INDEX idx_space_room_layouts_space_id_user_id
    ON spaces.space_room_layouts (space_id, user_id, updated_at DESC);
