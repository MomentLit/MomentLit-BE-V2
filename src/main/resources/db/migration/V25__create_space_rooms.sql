-- ============================================================
-- SPACE ROOM (3D 방 모델)
-- 공간의 360도 장면마다 하나씩 만들 수 있다(공간당 20개까지, 서비스에서 제한). 좌표는 모두 미터 단위.
-- 장면은 공간을 수정할 때 새로 저장되어 id가 바뀔 수 있어서, 만든 장면은 사진 URL(scene_image_url)로 기억한다.
-- ============================================================
CREATE TABLE spaces.space_rooms (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    space_id         BIGINT NOT NULL,
    name             VARCHAR(100) NOT NULL,
    sort_order       INTEGER NOT NULL,
    scene_image_url  VARCHAR(255),
    source           VARCHAR(20) NOT NULL,
    image_url        VARCHAR(255),
    ceiling_height   DOUBLE PRECISION NOT NULL,
    camera_height    DOUBLE PRECISION,
    area_m2          DOUBLE PRECISION NOT NULL,
    geometry         JSONB NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    updated_at       TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_space_rooms PRIMARY KEY (id)
);

CREATE INDEX idx_space_rooms_space_id
    ON spaces.space_rooms (space_id, sort_order);

-- ============================================================
-- SPACE ROOM LAYOUT (사용자가 저장한 가구 배치)
-- 로그인한 사용자가 3D 방에 놓아 본 가구. 방마다 이름을 붙여 여러 개(서비스에서 20개까지) 저장한다.
-- ============================================================
CREATE TABLE spaces.space_room_layouts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    room_id     BIGINT NOT NULL,
    space_id    BIGINT NOT NULL,
    user_id     VARCHAR(255) NOT NULL,
    name        VARCHAR(50) NOT NULL,
    furniture   JSONB NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_space_room_layouts PRIMARY KEY (id)
);

CREATE INDEX idx_space_room_layouts_room_id_user_id
    ON spaces.space_room_layouts (room_id, user_id, updated_at DESC);
