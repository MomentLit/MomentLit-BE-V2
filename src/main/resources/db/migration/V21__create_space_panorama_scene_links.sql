-- ============================================================
-- SPACE PANORAMA SCENE LINKS (360도 장면 사이 이동 화살표)
-- 한 장면에서 여러 장면으로 이동할 수 있도록 장면 사이 연결을 저장한다.
-- yaw는 출발 장면에서 화살표가 놓이는 수평 방향(라디안, 0 이상 2π 미만)이다.
-- ============================================================
CREATE TABLE spaces.space_panorama_scene_links (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    space_id        BIGINT NOT NULL,
    from_scene_id   BIGINT NOT NULL,
    to_scene_id     BIGINT NOT NULL,
    yaw             DOUBLE PRECISION NOT NULL,
    CONSTRAINT pk_space_panorama_scene_links PRIMARY KEY (id)
);

CREATE INDEX idx_space_panorama_scene_links_space_id
    ON spaces.space_panorama_scene_links (space_id);

-- 기존 장면은 등록 순서대로 앞뒤 장면을 잇는다(V20 동작 그대로).
-- 다음 장면은 정면(yaw 0), 이전 장면은 뒤쪽(yaw π)에 화살표를 둔다.
INSERT INTO spaces.space_panorama_scene_links (space_id, from_scene_id, to_scene_id, yaw)
SELECT current_scene.space_id, current_scene.id, next_scene.id, 0
FROM spaces.space_panorama_scenes current_scene
JOIN spaces.space_panorama_scenes next_scene
    ON next_scene.space_id = current_scene.space_id
    AND next_scene.sort_order = current_scene.sort_order + 1;

INSERT INTO spaces.space_panorama_scene_links (space_id, from_scene_id, to_scene_id, yaw)
SELECT next_scene.space_id, next_scene.id, current_scene.id, PI()
FROM spaces.space_panorama_scenes current_scene
JOIN spaces.space_panorama_scenes next_scene
    ON next_scene.space_id = current_scene.space_id
    AND next_scene.sort_order = current_scene.sort_order + 1;
