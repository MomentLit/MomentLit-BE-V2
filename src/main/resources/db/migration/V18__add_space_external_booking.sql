-- ============================================================
-- SPACE EXTERNAL BOOKING
-- 자체 홈페이지로 예약을 받는 공간은 정보만 노출하고 외부 링크로 연결한다.
-- 외부로 나가는 클릭은 space_external_booking_clicks에 기록한다.
-- ============================================================
ALTER TABLE spaces.spaces
    ADD COLUMN booking_type VARCHAR(20) NOT NULL DEFAULT 'INTERNAL',
    ADD COLUMN external_booking_url VARCHAR(2048);

ALTER TABLE spaces.spaces
    ADD CONSTRAINT chk_spaces_booking_type CHECK (booking_type IN ('INTERNAL', 'EXTERNAL'));

CREATE TABLE spaces.space_external_booking_clicks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    space_id   BIGINT NOT NULL,
    user_id    VARCHAR(255),
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_space_external_booking_clicks PRIMARY KEY (id)
);

CREATE INDEX idx_space_external_booking_clicks_space_id_created_at
    ON spaces.space_external_booking_clicks (space_id, created_at DESC);
