-- ============================================================
-- SPACE PANORAMA SCENES (360도 장면)
-- 한 공간에 360도 사진을 여러 장 두고, 등록 순서(sort_order)대로 앞뒤 장면으로 이동한다.
-- 이동 화살표는 순서만으로 정해지므로 장면 사이 링크는 따로 저장하지 않는다.
-- spaces.panorama_url은 하위 호환을 위해 남겨 두고, 첫 장면 URL과 같게 유지한다.
-- ============================================================
CREATE TABLE spaces.space_panorama_scenes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    space_id    BIGINT NOT NULL,
    image_url   VARCHAR(255) NOT NULL,
    name        VARCHAR(255),
    sort_order  INTEGER NOT NULL,
    CONSTRAINT pk_space_panorama_scenes PRIMARY KEY (id)
);

CREATE INDEX idx_space_panorama_scenes_space_id
    ON spaces.space_panorama_scenes (space_id, sort_order);

-- 기존 360도 사진은 그 공간의 첫 장면이 된다.
INSERT INTO spaces.space_panorama_scenes (space_id, image_url, sort_order)
SELECT id, panorama_url, 0
FROM spaces.spaces
WHERE panorama_url IS NOT NULL;
