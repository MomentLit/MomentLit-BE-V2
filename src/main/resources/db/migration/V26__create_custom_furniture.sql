-- 사용자가 직접 만든 가구("내 가구") — 사진으로 생성(RoomScan)하거나 GLB 파일을 올린다. 만든 사람만 본다.
-- 3D 방 배치에서는 type = 'u-' || id 로 가리킨다.
CREATE TABLE spaces.custom_furniture (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         VARCHAR(255) NOT NULL,
    name            VARCHAR(50) NOT NULL,
    mount           VARCHAR(10) NOT NULL,
    source          VARCHAR(10) NOT NULL,
    status          VARCHAR(12) NOT NULL,
    width           DOUBLE PRECISION,
    depth           DOUBLE PRECISION,
    height          DOUBLE PRECISION NOT NULL,
    model_url       VARCHAR(255),
    thumbnail_url   VARCHAR(255),
    failure_reason  VARCHAR(255),
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_custom_furniture PRIMARY KEY (id)
);

CREATE INDEX idx_custom_furniture_user_id
    ON spaces.custom_furniture (user_id, created_at DESC);
